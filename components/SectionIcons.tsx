const legacyValues: Record<string, string> = {
  Info: 'info',
  Completed: 'completed',
  Calendar: 'calendar',
  Clock: 'clock',
  Bell: 'bell',
  Lock: 'lock',
}

function iconTitle(name: string) {
  return name
    .replace(/([A-Z])([A-Z][a-z])/g, '$1 $2')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
}

export const sectionIconMap: Record<string, ComponentType<IconPropsWithoutSvgPath>> = {}
export const sectionIconOptions: SectionIconOption[] = []

for (const [name, Icon] of Object.entries(systemIconComponents)) {
  const value = legacyValues[name] || name
  sectionIconMap[name] = Icon
  sectionIconMap[value] = Icon
  sectionIconOptions.push({title: iconTitle(name), value, Icon})
}

sectionIconMap.help = HelpOutlineIcon
